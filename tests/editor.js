 const val=()=>pg.$eval('#code',e=>e.value);
 const reset=async(t,a,b)=>{await pg.$eval('#code',(e,[t,a,b])=>{e.value=t;e.focus();e.setSelectionRange(a===undefined?t.length:a,b===undefined?(a===undefined?t.length:a):b)},[t,a,b])};
