 await reset('');await pg.keyboard.type('if (a)');await key('Enter');
 await reset('void A() {}',10);await key('Enter');
 ok(await val()==='void A() {\n    \n}'&&(await sel())[0]===15,'{} 사이에서 엔터: 가운데 줄 들여쓰기, 커서 위치');
